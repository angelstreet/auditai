import { z } from 'zod';
import { analysisIdSchema, engagementIdSchema, isoDateTimeSchema, tenantIdSchema } from './ids.js';
import { competencyAxisSchema } from './template.js';

/**
 * Cross-team synergy entry (M13, FR-14, PRD §10).
 *
 * One row per recurrence of a maturity theme across two or more engagements within a single
 * tenant. The detection worker (a later M13 slice) groups approved-analysis themes by
 * `(axis, themeLabel)` and writes one row per group that crosses at least two engagements; the
 * `sourceAnalysisIds` + `sourceEngagementIds` JSONB arrays carry the provenance, the
 * `proposedFollowupPrompt` carries the suggested question to ask in the next interview round.
 *
 * The `synergyKey` is a stable hash of `(axis | lower(themeLabel))`; re-running the worker is
 * idempotent — a second run that touches the same surface does not create a new row unless the
 * underlying source set grew.
 */

export const synergyStatusSchema = z.enum(['detected', 'surfaced', 'dismissed', 'archived']);
export type SynergyStatus = z.infer<typeof synergyStatusSchema>;

/** Stable hash key for `(axis, lower(themeLabel))` — generated by the worker, validated here. */
export const synergyKeySchema = z
  .string()
  .min(8)
  .max(128)
  .regex(/^[a-z0-9:_-]+$/);
export type SynergyKey = z.infer<typeof synergyKeySchema>;

export const synergyIdSchema = z.string().uuid().brand<'SynergyId'>();
export type SynergyId = z.infer<typeof synergyIdSchema>;

/** The wire shape of a synergy row. */
export const synergySchema = z.object({
  id: synergyIdSchema,
  tenantId: tenantIdSchema,
  axis: competencyAxisSchema,
  themeLabel: z.string().min(3).max(200),
  /** Stable hash so the worker can upsert idempotently. */
  synergyKey: synergyKeySchema,
  /** IDs of the analyses that surfaced this theme; length >= 2 by construction. */
  sourceAnalysisIds: z.array(analysisIdSchema).min(2),
  /** Distinct engagement IDs derived from `sourceAnalysisIds`. */
  sourceEngagementIds: z.array(engagementIdSchema).min(2),
  /** Number of distinct engagements that contributed themes to this group. */
  occurrenceCount: z.number().int().min(2),
  /** Proposed follow-up interview question generated by the worker. */
  proposedFollowupPrompt: z.string().min(10).max(1_000),
  status: synergyStatusSchema,
  detectedAt: isoDateTimeSchema,
  surfacedAt: isoDateTimeSchema.nullable(),
  dismissedAt: isoDateTimeSchema.nullable(),
  createdAt: isoDateTimeSchema,
  updatedAt: isoDateTimeSchema,
});
export type Synergy = z.infer<typeof synergySchema>;

/**
 * The shape the detection worker sends to the data layer. The server fills `id` + timestamps
 * and the data layer derives `sourceEngagementIds` + `occurrenceCount` from the analysis IDs.
 */
export const synergyWriteSchema = z.object({
  tenantId: tenantIdSchema,
  axis: competencyAxisSchema,
  themeLabel: z.string().min(3).max(200),
  synergyKey: synergyKeySchema,
  sourceAnalysisIds: z.array(analysisIdSchema).min(2),
  proposedFollowupPrompt: z.string().min(10).max(1_000),
});
export type SynergyWrite = z.infer<typeof synergyWriteSchema>;
